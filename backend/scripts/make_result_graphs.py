def save(fig, name, title, finding, rows, header):
    fig.text(0.012, 0.975, title, fontsize=13.5, fontweight="bold", color=INK, va="top")
    fig.text(0.012, 0.925, finding, fontsize=10.5, color=INK2, va="top")
    fig.text(0.012, -0.03, "Source: reports/*.json, generated by the evaluation scripts (counts only)", fontsize=8, color=INK2, va="top")
    fig.savefig(OUT / f"{name}.png", dpi=170, bbox_inches="tight")
    plt.close(fig)
    with open(OUT / f"{name}.csv", "w", newline="") as f:
        w = csv.writer(f); w.writerow(header); w.writerows(rows)
    INDEX.append((name, title, finding))


def bars(ax, labels, values, color=BLUE, fmt="{:.1%}", horizontal=False, colors=None):
    pos = range(len(labels))
    cs = colors or [color] * len(labels)
    if horizontal:
        ax.barh(list(pos), values, color=cs, height=0.6)
        ax.set_yticks(list(pos), labels); ax.invert_yaxis()
        for i, v in enumerate(values):
            ax.text(v + 0.01 * max(values or [1]), i, fmt.format(v), va="center", fontsize=9, color=INK)
        ax.grid(axis="x", color=GRID, lw=0.8); ax.set_axisbelow(True)
    else:
        ax.bar(list(pos), values, color=cs, width=0.6)
        ax.set_xticks(list(pos), labels)
        for i, v in enumerate(values):
            ax.text(i, v + 0.012 * max(values or [1]), fmt.format(v), ha="center", fontsize=9.5, color=INK)
        ax.grid(axis="y", color=GRID, lw=0.8); ax.set_axisbelow(True)


def grouped(ax, labels, series, names, colors, fmt="{:.1%}", horizontal=False):
    n, k = len(labels), len(series)
    w = 0.8 / k
    for j, (vals, nm, c) in enumerate(zip(series, names, colors)):
        pos = [i - 0.4 + w * (j + 0.5) for i in range(n)]
        if horizontal:
            pv = [(p, v) for p, v in zip(pos, vals) if v is not None]
            ax.barh([p for p, _ in pv], [v for _, v in pv], height=w * 0.9, color=c, label=nm)
            gap = 0.008 * max([x for x in sum(series, []) if x is not None] or [1])
            for p, v in pv:
                ax.text(v + gap, p, fmt.format(v), va="center", fontsize=8, color=INK)
        else:
            ax.bar(pos, vals, width=w * 0.9, color=c, label=nm)
            for p, v in zip(pos, vals):
                ax.text(p, v + 0.012, fmt.format(v), ha="center", fontsize=8.5, color=INK)
    if horizontal:
        ax.set_yticks(range(n), labels); ax.invert_yaxis(); ax.grid(axis="x", color=GRID, lw=0.8)
    else:
        ax.set_xticks(range(n), labels); ax.grid(axis="y", color=GRID, lw=0.8)
    ax.set_axisbelow(True)
    ax.legend(frameon=False, loc="lower right" if horizontal else "upper right", fontsize=9)


