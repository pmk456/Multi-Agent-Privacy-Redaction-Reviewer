"""File format for the synthetic cross-document privacy dataset.

backend/tests/fixtures/synthetic_cross_document.json is generated by
backend/scripts/make_synthetic_dataset.py and validated against `SyntheticDataset`.

Everything in it is fictional. The dataset is ground truth for Agent 5 (adversarial /
re-identification) and for integration tests: it says, independently of any agent, which
people ARE re-identifiable by combining documents and which are NOT.

Vocabulary
----------
registry      the hidden "outside world": ~40 fictional people with quasi-identifying
              attributes. Anonymity-set size k is computed against it.
mention       a span of a document, its canonical entity type, and (hidden ground truth)
              which registry person it is about. `attribute`/`attribute_value` say which
              registry attribute the mention reveals, normalised to the registry's form
              (e.g. the text "36" reveals AGE = "30-39").
planted risk  one per target person: the attributes revealed about them across `doc_ids`,
              and k = how many registry people share all of them.
"""

from __future__ import annotations

from typing import Literal, Optional

from pydantic import BaseModel, Field, model_validator

from privacy_review.schemas.policy import RiskLevel, Strategy

AttributeKey = Literal[
    "OCCUPATION", "ORGANIZATION", "DEPARTMENT", "LOCATION", "AGE", "DEMOGRAPHIC", "EVENT"
]
"""Registry attributes a mention can reveal. DEPARTMENT mentions have entity_type
ORGANIZATION; DEMOGRAPHIC here means gender (the only demographic the registry models)."""

ATTRIBUTE_FIELD: dict[str, str] = {
    "OCCUPATION": "occupation",
    "ORGANIZATION": "organization",
    "DEPARTMENT": "department",
    "LOCATION": "city",
    "AGE": "age_band",
    "DEMOGRAPHIC": "gender",
    "EVENT": "events",            # set membership, not equality
}

MentionType = Literal[
    "PERSON", "EMAIL_ADDRESS", "PHONE_NUMBER", "OCCUPATION", "ORGANIZATION", "LOCATION",
    "AGE", "DATE", "DATE_OF_BIRTH", "POSTAL_CODE", "DEMOGRAPHIC", "EVENT",
    "MEDICAL_CONDITION", "GOVERNMENT_ID", "RECORD_IDENTIFIER",
]

DocType = Literal[
    "hr_record", "news_item", "attendee_list", "support_ticket", "leave_note",
    "internal_memo", "speaker_bio", "alumni_newsletter",
]

EdgeCaseName = Literal[
    "name_variants_same_person",
    "shared_surname_different_people",
    "same_email_two_documents",
    "no_name_still_identifying",
    "dob_postcode_gender",
    "medical_condition_with_name",
    "demographic_about_named_person",
    "isolated_dateline",
    "conflicting_city",
    "organisation_only_document",
]


class RegistryPerson(BaseModel):
    person_id: str
    name: str
    is_target: bool
    occupation: str
    organization: str
    department: str
    city: str
    age_band: str = Field(pattern=r"^\d0-\d9$")
    gender: Literal["female", "male"]
    events: list[str] = Field(default_factory=list)


class SyntheticDocument(BaseModel):
    doc_id: str
    doc_type: DocType
    text: str


class _Located(BaseModel):
    doc_id: str
    start: int = Field(ge=0)
    end: int

    @model_validator(mode="after")
    def _ordered(self):
        if self.end <= self.start:
            raise ValueError("end must be greater than start")
        return self


class Mention(_Located):
    entity_type: MentionType
    person_id: Optional[str] = Field(description="Who the mention is about. None = nobody.")
    value_kind: str = Field(min_length=1, description="Surface form, e.g. initial_surname, dateline.")
    sentence_index: int = Field(ge=0, description="0-based sentence (or list line) in the document.")
    attribute: Optional[AttributeKey] = None
    attribute_value: Optional[str] = None
    contradicts_registry: bool = Field(
        default=False, description="The document states a value that disagrees with the registry."
    )

    @model_validator(mode="after")
    def _attribute_pair(self):
        if (self.attribute is None) != (self.attribute_value is None):
            raise ValueError("attribute and attribute_value go together")
        if self.attribute is not None and self.person_id is None:
            raise ValueError("an attribute must be about a person")
        return self


class ExpectedStrategy(_Located):
    entity_type: MentionType
    expected_strategy: Strategy
    risk: RiskLevel
    fired_rules: list[str] = Field(default_factory=list)
    why: str


class PlantedRisk(BaseModel):
    risk_id: str
    person_id: str
    doc_ids: list[str] = Field(min_length=1)
    combined_attribute_types: list[AttributeKey] = Field(min_length=1)
    combined_attributes: dict[str, str]
    anonymity_set_size: int = Field(ge=1)
    reidentifiable: bool
    anonymity_set_size_after_first_pass: int = Field(
        ge=1, description="k over the attributes still readable after the expected first-pass strategies."
    )
    survives_first_pass: bool
    why: str

    @model_validator(mode="after")
    def _consistent(self):
        if self.reidentifiable != (self.anonymity_set_size == 1):
            raise ValueError("reidentifiable must equal (anonymity_set_size == 1)")
        if self.survives_first_pass != (self.anonymity_set_size_after_first_pass == 1):
            raise ValueError("survives_first_pass must equal (anonymity_set_size_after_first_pass == 1)")
        if sorted(self.combined_attribute_types) != sorted(self.combined_attributes):
            raise ValueError("combined_attribute_types must be the keys of combined_attributes")
        return self


class EdgeCase(BaseModel):
    case: EdgeCaseName
    doc_ids: list[str] = Field(min_length=1)
    expected_behaviour: str


class SyntheticDataset(BaseModel):
    version: str = "1.0"
    seed: int = 247
    threat_model: str
    registry: list[RegistryPerson]
    documents: list[SyntheticDocument]
    mentions: list[Mention]
    expected_strategies: list[ExpectedStrategy]
    planted_risks: list[PlantedRisk]
    edge_cases: list[EdgeCase]

    @model_validator(mode="after")
    def _references(self):
        doc_ids = [d.doc_id for d in self.documents]
        person_ids = [p.person_id for p in self.registry]
        if len(set(doc_ids)) != len(doc_ids):
            raise ValueError("duplicate doc_id")
        if len(set(person_ids)) != len(person_ids):
            raise ValueError("duplicate person_id")
        texts = {d.doc_id: d.text for d in self.documents}
        people = set(person_ids)
        for item in [*self.mentions, *self.expected_strategies]:
            if item.doc_id not in texts:
                raise ValueError(f"unknown doc_id {item.doc_id}")
            if item.end > len(texts[item.doc_id]):
                raise ValueError(f"span out of bounds in {item.doc_id}")
        for m in self.mentions:
            if m.person_id is not None and m.person_id not in people:
                raise ValueError(f"unknown person_id {m.person_id}")
        for r in self.planted_risks:
            if r.person_id not in people or not set(r.doc_ids) <= set(texts):
                raise ValueError(f"planted risk {r.risk_id} references unknown ids")
        for e in self.edge_cases:
            if not set(e.doc_ids) <= set(texts):
                raise ValueError(f"edge case {e.case} references unknown documents")
        return self

    def person(self, person_id: str) -> RegistryPerson:
        return next(p for p in self.registry if p.person_id == person_id)

    def text(self, doc_id: str) -> str:
        return next(d.text for d in self.documents if d.doc_id == doc_id)
